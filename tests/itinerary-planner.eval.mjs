import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const c={window:{},TextEncoder};vm.createContext(c);
for(const f of ['data.js','journey-presentation-data.js','explore-presentation-data.js','search-entity-registry.js','onboard-lookup-data.js','itinerary-planner.js'])vm.runInContext(fs.readFileSync(f,'utf8'),c);
const source=vm.runInContext('({schedule:cruiseSchedule,decks:deckGuideData,shows:showGuideData})',c);
const w=c.window,p=w.ITINERARY_PLANNER;
const options=p.candidates({...source,registry:w.SEARCH_ENTITY_REGISTRY,presentation:w.JOURNEY_PRESENTATION_DATA,explore:w.EXPLORE_PRESENTATION,lookup:w.ONBOARD_LOOKUP_DATA});
const model=p.create({...source,presentation:w.JOURNEY_PRESENTATION_DATA,options});
const original=JSON.stringify(source.schedule), empty=model.empty();
const id='search-schedule-day2-2-0';
const values=structuredClone(model.originals.get(id).values);
let draft=model.edit(empty,id,{...values,candidate:'entity:mowglis-eatery',time:'12:30',backup:true});
assert.equal(draft.edits[id].time.value,'12:30');
assert.equal(draft.edits[id].position,undefined,'only changed fields stored');
let event=model.effective(draft).flatMap(d=>d.periods.flatMap(p=>p.events)).find(e=>e.id===id);
assert.equal(event.local.display.shortTitle,'毛克利餐館');
assert.equal(event.local.display.menu[0].id,'mowgli');
assert.equal(event.local.display.status,'backup');
assert.equal(JSON.stringify(source.schedule),original);
assert.equal(model.effective(draft).flatMap(d=>d.periods.flatMap(p=>p.events)).length,38);
assert.equal(model.parse(JSON.stringify(draft)).edits[id].candidate.value,'entity:mowglis-eatery');
draft=model.edit(draft,id,{...event.local.values,position:{dayId:'day3',periodIndex:2,rank:-100}});
assert.equal(model.effective(draft)[2].periods[2].events[0].id,id);
assert(!model.effective(draft)[1].periods.flatMap(p=>p.events).some(e=>e.id===id));
assert.equal(model.originals.size,38);
for(const protectedId of ['search-schedule-day1-2-0','search-schedule-day2-4-0','search-schedule-day3-4-0','search-schedule-day3-royal-gathering','search-schedule-day1-1-3']) {
    const o=model.originals.get(protectedId);assert(o?.protected,protectedId);
    assert.throws(()=>model.edit(empty,protectedId,{...o.values,time:'改成晚上'}),/請先確認/);
    assert(model.edit(empty,protectedId,{...o.values,time:'改成晚上'},true).edits[protectedId]);
}
const updated=structuredClone(source.schedule);
updated[1].periods[2].events[0].time='13:00';
const newer=p.create({schedule:updated,presentation:w.JOURNEY_PRESENTATION_DATA,options});
assert.deepEqual(Array.from(newer.conflicts(draft),x=>x.field),['time']);
event=newer.effective(draft)[2].periods[2].events[0];
assert.equal(event.local.values.time,'13:00','conflicting field falls back to official until resolved');
assert.equal(event.local.values.candidate,'entity:mowglis-eatery');
assert.throws(()=>newer.resolve(draft,{}),/每一項/);
assert.equal(newer.resolve(draft,{[id+':time']:'draft'}).edits[id].time.base,newer.originals.get(id).bases.time);
assert.equal(newer.resolve(draft,{[id+':time']:'official'}).edits[id].time,undefined);
const missing=structuredClone(draft);missing.edits[id].candidate.value='entity:removed';
assert(model.conflicts(missing)[0].missing);
assert.throws(()=>model.edit(empty,id,{...values,candidate:'entity:removed'}),/候選/);
for(const raw of ['bad JSON','[]',JSON.stringify({...empty,schemaVersion:2}),JSON.stringify({...empty,tripId:'other'}),JSON.stringify({...empty,extra:'bad'}),' '.repeat(262145)])assert.throws(()=>model.parse(raw));
const malicious=JSON.stringify(empty).replace('"edits":{}','"edits":{"__proto__":{}}');assert.throws(()=>model.parse(malicious));
assert.equal(options.length,new Set(options.map(x=>x.id)).size);
assert.equal(options.find(x=>x.id==='entity:pizza-planet').menu[0].id,'pizza-planet');
assert(!options.find(x=>x.id==='entity:pizza-planet').menu.some(x=>x.id==='pixar'));
assert.equal(options.filter(x=>x.id.startsWith('activity:')).length,w.EXPLORE_PRESENTATION.groupActivities(w.ONBOARD_LOOKUP_DATA.records).length);
assert(options.every(x=>!('sourceTimeHint' in x) && !('time' in x)),'no historic times are suggested');
assert(options.some(x=>x.id==='show:lets-set-sail-show') && options.some(x=>x.id==='show:baymax-super-exercise-expo'),'composite show resolves to an entity');
assert.equal(JSON.stringify(source.schedule),original);
console.log('Planner: 38 stable slots, concrete candidates, protection, changes-only drafts, strict import, per-field reconciliation and unchanged originals PASS.');
