import assert from 'node:assert/strict';
import fs from 'node:fs';
import http from 'node:http';
import os from 'node:os';
import path from 'node:path';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root=path.resolve('.'), output=path.join(os.tmpdir(),'cruise-explore-phase2-qa');
fs.mkdirSync(output,{recursive:true});
const server=http.createServer((req,res)=>{
    const url=new URL(req.url,'http://localhost');
    const file=path.resolve(root,'.'+decodeURIComponent(url.pathname.endsWith('/')?url.pathname+'index.html':url.pathname));
    if(!file.startsWith(root+path.sep)||!fs.existsSync(file)){res.writeHead(404).end();return;}
    res.setHeader('Content-Type',({'.html':'text/html','.js':'text/javascript','.css':'text/css','.json':'application/json'})[path.extname(file)] || 'application/octet-stream');
    fs.createReadStream(file).pipe(res);
});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const base=`http://127.0.0.1:${server.address().port}/`;
const browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL||'msedge',headless:true});
try {
    for (const width of [360,390,1440]) {
        const context=await browser.newContext({viewport:{width,height:900},serviceWorkers:'block',reducedMotion:'reduce'});
        const page=await context.newPage(), errors=[], requests=[];
        page.on('pageerror',error=>errors.push(error.message));
        page.on('request',r=>requests.push(r.url()));
        await page.addInitScript(()=>{window.__SEARCH_TEST_HOOKS__={};});
        await page.goto(base+'#explore');
        assert.equal(await page.locator('#deck-filter').inputValue(),'deck17');
        assert.equal(await page.locator('[data-explore-tab]').count(),2);
        await page.locator('#deck-filter').selectOption('deck10');
        assert(await page.locator('#search-deck-deck10-4').isVisible());
        assert(await page.locator('#search-show-garden-shows-0').isVisible());
        assert(await page.locator('#search-show-open-air-night-0').isVisible());
        assert.equal(await page.locator('.floor-activity').count(),0,'activity bodies are lazy');
        await page.screenshot({path:path.join(output,`floor10-${width}.png`)});
        await page.locator('#search-show-open-air-night-0-detail > summary').click();
        await page.locator('#search-show-open-air-night-0 .entity-links a[href="#search-deck-deck10-1"]').click();
        await page.waitForFunction(()=>document.getElementById('search-deck-deck10-1-detail').open);
        await page.goBack();
        await page.waitForFunction(()=>!document.getElementById('search-deck-deck10-1-detail').open);
        assert(await page.locator('#search-show-open-air-night-0-detail').evaluate(el=>el.open),'same-floor return restores only the original disclosures');
        await page.locator('[data-purpose="restaurant"]').click();
        assert.equal(await page.locator('.show-item').count(),0);
        assert(await page.locator('#search-deck-deck10-4').isVisible());
        await page.locator('[data-purpose="shows"]').click();
        assert.equal(await page.locator('#deck-filter').inputValue(),'deck10');
        assert.equal(await page.locator('.facility-card').count(),0);
        await page.locator('#venue-activities-garden > summary').click();
        await page.waitForSelector('#venue-activities-garden .floor-activity');
        const expected=await page.evaluate(()=>EXPLORE_PRESENTATION.groupActivities(ONBOARD_LOOKUP_DATA.records).filter(g=>g.venue.id==='garden').length);
        assert.equal(await page.locator('#venue-activities-garden .floor-activity').count(),expected,'all venue matches, no top-N cap');
        const firstActivity=page.locator('#venue-activities-garden .floor-activity').first();
        await firstActivity.locator('summary').click();
        const activityId=await firstActivity.getAttribute('id');
        await page.locator('#venue-activities-garden > a').click();
        await page.waitForFunction(()=>document.activeElement?.id==='search-deck-deck10-0');
        await page.goBack();
        await page.waitForFunction(id=>document.getElementById(id)?.open,activityId);
        assert.equal(await page.locator('#deck-filter').inputValue(),'deck10');
        assert.equal(await page.locator('[data-purpose="shows"]').getAttribute('aria-pressed'),'true');
        assert(await page.locator('#venue-activities-garden > a').evaluate(el=>el===document.activeElement));
        await page.reload();
        assert.equal(await page.locator('#deck-filter').inputValue(),'deck10','last explicitly selected floor persists');
        await page.locator('#deck-filter').selectOption('deck7');
        await page.locator('[data-purpose="shows"]').click();
        assert(await page.locator('#search-show-stage-musicals-0').isVisible());
        await page.locator('#venue-activities-cinema > summary').click();
        await page.waitForSelector('#venue-activities-cinema .floor-activity');
        assert.match(await page.locator('#venue-activities-cinema').textContent(),/Family Movie Fun Time/);
        await page.locator('#deck-filter').selectOption('unknown');
        await page.locator('#venue-activities-unknown > summary').click();
        await page.waitForSelector('#venue-activities-unknown .floor-activity');
        assert.match(await page.locator('#venue-activities-unknown').textContent(),/D Lounge/);
        await page.locator('[data-explore-tab="playbook"]').click();
        const seen=[];
        for(const topic of ['departure','dining','shows-photos','family','daily','concierge','departure-home']){
            await page.locator(`[data-playbook-mission="${topic}"]`).click();
            seen.push(...await page.locator('.playbook-card').evaluateAll(nodes=>nodes.map(n=>n.id)));
            assert(await page.evaluate(()=>[...document.querySelectorAll('.playbook-card')].every(card=>{
                const item=playbookGuideData.flatMap(m=>m.items).find(i=>i.id===card.id);
                return ['title','whenToUse','action','caution','tripFit','sourceNote'].every(key=>{
                    if(!item[key]) return true;
                    const text=document.createElement('div');text.innerHTML=item[key];
                    const normalize=s=>s.replace(/\s+/g,' ').trim();
                    return normalize(card.textContent).includes(normalize(text.textContent));
                });
            })),'all original tip fields remain readable');
        }
        assert.equal(new Set(seen).size,41);
        assert.equal(seen.length,41,'each original tip appears in exactly one category');
        assert(await page.evaluate(()=>window.__SEARCH_TEST_HOOKS__.getSearchDocuments().some(doc=>doc.id==='search-playbook-daily-ops-3' && doc.locationLabel.includes('吃喝與點餐') && doc.keywords.includes('房務怎麼點、要等多久'))),'short title and current topic are searchable without losing old titles');
        await page.locator('[data-playbook-mission="dining"]').click();
        await page.locator('#search-playbook-daily-ops-3 > summary').click();
        assert.match(await page.locator('#search-playbook-daily-ops-3').textContent(),/Room Service/);
        await page.screenshot({path:path.join(output,`tips-${width}.png`)});
        await page.locator(width < 761 ? '.mobile-nav [data-view-link="prepare"]' : '.nav-links [data-view-link="prepare"]').click();
        await page.goBack();
        await page.waitForFunction(()=>document.querySelector('#search-playbook-daily-ops-3')?.open);
        assert.equal(await page.locator('[data-playbook-mission="dining"]').getAttribute('aria-pressed'),'true');
        await page.goto(base+'#search-playbook-concierge-plus-6');
        assert.equal(await page.locator('[data-playbook-mission="shows-photos"]').getAttribute('aria-pressed'),'true');
        await page.waitForFunction(()=>document.querySelector('#search-playbook-concierge-plus-6')?.open);
        await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
        assert(await page.locator('#search-playbook-concierge-plus-6').evaluate(el=>el.open));
        await page.goto(base+'#explore/shows');
        assert.equal(await page.locator('#deck-filter').inputValue(),'all');
        assert.equal(await page.locator('.show-item').count(),8);
        await page.locator('#deck-filter').selectOption('deck10');
        await page.evaluate(()=>document.documentElement.style.fontSize='200%');
        await page.addStyleTag({content:'*{line-height:1.5!important;letter-spacing:.12em!important;word-spacing:.16em!important;} p{margin-bottom:2em!important;}'});
        assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'large text floor layout fits');
        await page.locator('#venue-activities-garden > summary').click();
        await page.waitForSelector('#venue-activities-garden .floor-activity');
        assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'expanded activity layout fits');
        await page.screenshot({path:path.join(output,`large-${width}.png`)});
        assert(!requests.some(url=>url.includes('menu-lookup-data.js')),'browsing never eagerly loads menus');
        assert.deepEqual(errors,[]);
        await context.close();
        console.log('Floor, activity, topic, history and zoom checks passed:',width);
    }
} finally {await browser.close();server.closeAllConnections();await new Promise(resolve=>server.close(resolve));}
