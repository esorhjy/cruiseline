import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const source = fs.readFileSync('data.js', 'utf8');
const data = vm.runInNewContext(`${source}\n({cruiseSchedule, checklistData, deckGuideData, showGuideData, playbookGuideData})`);
const events = data.cruiseSchedule.flatMap(day => day.periods.flatMap(period => period.events));
const deck = id => data.deckGuideData.find(item => item.id === id);
const text = value => JSON.stringify(value);
const dinnerIds = ['search-schedule-day1-2-0', 'search-schedule-day2-4-0', 'search-schedule-day3-4-0'];
const dinners = dinnerIds.map(id => events.find(event => event.id === id));
assert.equal(dinners.length, 3);
assert(dinners.every(event => event.time === '20:15' && text(event).includes('可能調整 15 分鐘')));
['Animator’s Table', 'Enchanted Summer', 'Hollywood Spotlight'].forEach((name, index) => assert(dinners[index].title.includes(name)));
assert(!/第一時段|First Seating|17:45/.test(source));
const day3 = data.cruiseSchedule[2].periods.flatMap(period => period.events);
const royal = day3.find(event => event.id === 'search-schedule-day3-royal-gathering');
assert.equal(royal.time, '08:30');
assert.match(text(royal), /1\/27 08:30/);
assert(day3.indexOf(royal) < day3.findIndex(event => event.id === 'search-schedule-day3-0-0'));
assert(day3.findIndex(event => event.id === 'search-schedule-day3-0-0') < day3.findIndex(event => event.id === 'search-schedule-day3-moana'));
assert.match(text(day3.find(event => event.id === 'search-schedule-day3-moana')), /不保證上午演出/);
assert(!day3.some(event => ['07:00–08:00', '08:00–10:00', '10:00–11:00'].includes(event.time)));
const drill = events.find(event => event.title.includes('Mandatory Guest'));
assert.equal(drill.time, '依當天集合通知');
assert.match(text(data.cruiseSchedule[0].goals), /非正式節目表/);
const openHouse = events.filter(event => /Oceaneer Club Open House/.test(event.title));
assert.equal(openHouse.length, 1);
assert.match(text(openHouse[0]), /不是託管/);
assert(!events.some(event => /澤澤、小寶.*Edge/.test(event.title)));
assert.match(text(deck('deck17').facilities[1]), /4–8/);
assert.match(text(deck('deck17').facilities[1]), /僅彤妹/);
assert.match(text(deck('deck19').facilities[1]), /122/);
assert.match(text(deck('deck19').facilities[1]), /水鞋/);
assert.match(text(deck('deck18').facilities[1]), /未滿 12/);
assert.match(text(deck('deck8').facilities[0]), /3–10/);
const fireworks = data.showGuideData.find(group => group.id === 'open-air-night').shows[1];
assert.match(fireworks.tripLink, /不固定最後一晚/);
const items = data.checklistData.flatMap(group => group.items);
assert.equal(new Set(items.map(item => item.id)).size, items.length);
for (const id of ['both-cabins-balance-202609', 'hotel-20270124', 'other-family-flights', 'ground-transfers-three-legs', 'cruise-insurance-review', 'school-calendars', 'photo-two-families-scope']) {
  assert(items.some(item => item.id === id), `missing pending task ${id}`);
}
assert.match(items.find(item => item.id === 'sgac-arrival-20270124').text, /1\/22–1\/24/);
assert.match(items.find(item => item.id === 'sgac-return-20270128').text, /1\/26–1\/28/);
assert(!items.some(item => item.checked || item.completed));
const daily = data.playbookGuideData.find(group => group.id === 'daily-ops').items;
assert.match(text(daily[3]), /US\$5/);
assert.match(text(daily[3]), /18%/);
assert.match(text(daily[3]), /早餐掛卡/);
assert.match(text(daily[6]), /未滿 21/);
assert.match(text(daily[6]), /不要試下載/);
assert(!text(daily[6]).includes('至少一次下載'));
const family = data.playbookGuideData.find(group => group.id === 'family-planning').items;
assert.match(text(family[0]), /停止等候/);
assert.match(text(family[1]), /不代表每場/);
assert.match(text(family[2]), /無證據/);
assert.match(text(family[3]), /不是入住後評價/);
const html = fs.readFileSync('index.html', 'utf8');
assert(!html.includes('海洋俱樂部註冊 (13:20-14:10)'));
assert(!html.includes('1/27 晚上 10:00 前'));
assert(!html.includes('id="menu-lookup"'));
console.log('Family plan: schedule, eligibility, pending tasks and provenance passed.');
